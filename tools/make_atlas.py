#!/usr/bin/env python3
"""Writes lua/atlas.lua: where each button's picture sits in Forever's art, from art/atlas-members.csv.

art/atlas-members.csv was cut from wago.tools' UiTextureAtlasMember for build 1.60.1.70790: file, name, left, top, right,
bottom, atlas width, atlas height. Where a set has no picture for a button, it borrows the generic set's.
"""
import csv
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
BUTTONS = ["SOUTH", "EAST", "WEST", "NORTH", "UP", "RIGHT", "DOWN", "LEFT", "LB", "RB", "LT", "RT", "START", "BACK", "L3", "R3"]
NAMES = {
    "ltr": dict(SOUTH="a", EAST="b", WEST="x", NORTH="y", UP="up", RIGHT="right", DOWN="down", LEFT="left", LB="lshoulder",
                RB="rshoulder", LT="ltrigger", RT="rtrigger", START="menu", BACK="view"),
    "shp": dict(SOUTH="cross", EAST="circle", WEST="square", NORTH="triangle", UP="up", RIGHT="right", DOWN="down", LEFT="left",
                LB="lshoulder", RB="rshoulder", LT="ltrigger", RT="rtrigger", START="menu", BACK="share", L3="lstickin", R3="rstickin"),
    "rev": dict(SOUTH="b", EAST="a", WEST="y", NORTH="x", LB="lshoulder", RB="rshoulder", LT="ltrigger", RT="rtrigger",
                START="plus", BACK="minus"),
    "gen": dict(SOUTH="1", EAST="2", WEST="3", NORTH="4", UP="up", RIGHT="right", DOWN="down", LEFT="left", LB="lshoulder",
                RB="rshoulder", LT="ltrigger", RT="rtrigger", START="forward", BACK="back", L3="lstickin", R3="rstickin"),
}


def main():
    rows = {r[1]: r for r in csv.reader(open(os.path.join(ROOT, "art", "atlas-members.csv")))}
    out = ["-- Generated by tools/make_atlas.py. Where each button's picture sits in Forever's art.\nlocal _, G = ...\nG.Atlas = {\n"]
    for family in ("ltr", "shp", "rev", "gen"):
        out.append("\t%s = {\n" % family)
        for button in BUTTONS:
            name = NAMES[family].get(button)
            row = rows.get("gamepad_%s_%s_64" % (family, name)) if name else None
            art = family
            if not row:
                row = rows["gamepad_gen_%s_64" % NAMES["gen"][button]]
                art = "gen"
            left, top, right, bottom, width, height = [int(x) for x in row[2:8]]
            out.append('\t\t%s = { "%s", %.6f, %.6f, %.6f, %.6f },\n' % (button, art, left / width, right / width, top / height, bottom / height))
        out.append("\t},\n")
    out.append("}\n")
    open(os.path.join(ROOT, "lua", "atlas.lua"), "w").write("".join(out))


if __name__ == "__main__":
    main()
